"""Regenerate src/exp_table.rs: 2^(j/256), j in 0..256, correctly rounded to f64.

Run from this directory: `python gen_exp_table.py` (standard library only).
"""

import struct
from decimal import Decimal, getcontext

getcontext().prec = 60
ln2 = Decimal(2).ln()
rows = [
    "    0x%016x," % struct.unpack("<Q", struct.pack("<d", float((ln2 * j / 256).exp())))[0]
    for j in range(256)
]
offset = float(Decimal("1.5552") + Decimal("0.968").ln())
src = f"""//! Generated by `gen_exp_table.py`: `2^(j/256)` for `j` in `0..256`, each
//! correctly rounded to f64 (60-digit `decimal`), as bit patterns.

pub const EXP2_TABLE_BITS: [u64; 256] = [
{chr(10).join(rows)}
];

/// `1.5552 + ln 0.968`, so `exp(0.0875 T + this) = 0.968 exp(0.0875 T + 1.5552)`.
pub const HEAT_OFFSET: f64 = {offset!r};
"""
with open("src/exp_table.rs", "w", newline="\n") as f:
    f.write(src)
